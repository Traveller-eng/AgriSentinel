def t(key: str) -> str:
    """
    Look up translated string for the currently active language in st.session_state.
    Falls back to English if key is missing in active language.
    """
    lang = st.session_state.get("lang", "en")
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    return lang_dict.get(key, TRANSLATIONS["en"].get(key, key))


def render_language_selector(key_prefix: str = "global"):
    """
    Render a 4-language pill selector row in the top-right of headers.
    Options: EN ('en'), हिन्दी ('hi'), తెలుగు ('te'), मराठी ('mr').
    Active language is styled in primary brand green, passive languages as outline.
    Persists choice to st.session_state['lang'] and triggers a rerun on change.
    """
    current_lang = st.session_state.get("lang", "en")
    if current_lang not in SUPPORTED_LANGUAGES:
        current_lang = "en"
        st.session_state["lang"] = "en"

    cols = st.columns([1, 1, 1, 1], gap="small")
    for idx, (code, label) in enumerate(SUPPORTED_LANGUAGES.items()):
        with cols[idx]:
            is_active = (code == current_lang)
            if st.button(
                label,
                key=f"lang_btn_{key_prefix}_{code}",
                type="primary" if is_active else "secondary",
                use_container_width=True
            ):
                if current_lang != code:
                    st.session_state["lang"] = code
                    st.rerun()
